// Convierte un recorrido [[lat, lng], ...] al formato { lat, lng } de Google Maps.
export function toLatLngPath(path) {
  if (!Array.isArray(path)) throw new TypeError('path debe ser un arreglo de [lat, lng]');
  return path.map((p, i) => {
    if (!Array.isArray(p) || p.length !== 2 || !p.every((v) => typeof v === 'number' && Number.isFinite(v))) {
      throw new TypeError(`path[${i}] debe ser [lat, lng] numerico`);
    }
    return { lat: p[0], lng: p[1] };
  });
}

